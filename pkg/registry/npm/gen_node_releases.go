// This program generates node_releases.go from the index of unofficial node
// builds, keeping the releases with a linux-x64-musl build.
//
// Run: go generate ./pkg/registry/npm
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"net/http"
	"os"
	"slices"
	"strings"
	"time"

	"github.com/google/oss-rebuild/internal/semver"
	"github.com/pkg/errors"
)

const (
	indexURL   = "https://unofficial-builds.nodejs.org/download/release/index.json"
	outputFile = "node_releases.go"
)

type release struct {
	Version string   `json:"version"`
	NPM     string   `json:"npm"`
	Date    string   `json:"date"`
	Files   []string `json:"files"`
}

func main() {
	log.SetFlags(0)
	releases, err := fetchReleases()
	if err != nil {
		log.Fatal(errors.Wrap(err, "fetching releases"))
	}
	if err := writeTable(releases); err != nil {
		log.Fatal(errors.Wrap(err, "writing table"))
	}
	log.Printf("Wrote %d releases to %s", len(releases), outputFile)
}

// fetchReleases returns the releases with a linux-x64-musl build, newest first.
func fetchReleases() ([]release, error) {
	resp, err := http.Get(indexURL)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, errors.Errorf("unexpected status %s", resp.Status)
	}
	var index []release
	if err := json.NewDecoder(resp.Body).Decode(&index); err != nil {
		return nil, errors.Wrap(err, "parsing index")
	}
	var releases []release
	for _, r := range index {
		if !slices.Contains(r.Files, "linux-x64-musl") {
			continue
		}
		r.Version = strings.TrimPrefix(r.Version, "v")
		if _, err := semver.New(r.Version); err != nil {
			return nil, errors.Errorf("invalid version %q", r.Version)
		}
		if _, err := semver.New(r.NPM); err != nil {
			return nil, errors.Errorf("%s: invalid npm version %q", r.Version, r.NPM)
		}
		if _, err := time.Parse(time.DateOnly, r.Date); err != nil {
			return nil, errors.Errorf("%s: invalid date %q", r.Version, r.Date)
		}
		releases = append(releases, r)
	}
	slices.SortFunc(releases, func(a, b release) int { return semver.Cmp(b.Version, a.Version) })
	return releases, nil
}

const header = `// Copyright 2026 Google LLC
// SPDX-License-Identifier: Apache-2.0

// Code generated by gen_node_releases.go. DO NOT EDIT.
// Regenerate: go generate ./pkg/registry/npm

package npm

// UnofficialNodeReleases lists the node releases with a linux-x64-musl build,
// newest first.
var UnofficialNodeReleases = []NodeRelease{
`

func writeTable(releases []release) error {
	var buf bytes.Buffer
	buf.WriteString(header)
	for _, r := range releases {
		fmt.Fprintf(&buf, "newNodeRelease(%q, %q, %q),\n", r.Version, r.NPM, r.Date)
	}
	buf.WriteString("}\n")
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return errors.Wrap(err, "formatting generated code")
	}
	return os.WriteFile(outputFile, formatted, 0644)
}
