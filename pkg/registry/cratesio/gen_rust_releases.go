// This program generates rust_releases.go from the release notes on the
// stable branch of rust-lang/rust, probing static.rust-lang.org for the
// x86_64-unknown-linux-musl toolchain of each release.
//
// Run: go generate ./pkg/registry/cratesio
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"regexp"

	"github.com/pkg/errors"
)

const (
	// NOTE: The stable branch lists only released versions.
	notesURL   = "https://raw.githubusercontent.com/rust-lang/rust/stable/RELEASES.md"
	muslURL    = "https://static.rust-lang.org/dist/%s/rust-%s-x86_64-unknown-linux-musl.tar.gz"
	outputFile = "rust_releases.go"
)

// headingRE matches release headings like "Version 1.72.1 (2023-09-19)".
var headingRE = regexp.MustCompile(`(?m)^Version (\S+) \((\d{4}-\d{2}-\d{2})\)$`)

type release struct {
	version, date string
	musl          bool
}

func main() {
	log.SetFlags(0)
	releases, err := fetchReleases()
	if err != nil {
		log.Fatal(errors.Wrap(err, "fetching releases"))
	}
	if err := writeTable(releases); err != nil {
		log.Fatal(errors.Wrap(err, "writing table"))
	}
	log.Printf("Wrote %d releases to %s", len(releases), outputFile)
}

// fetchReleases returns the releases in the release notes, newest first.
func fetchReleases() ([]release, error) {
	resp, err := http.Get(notesURL)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, errors.Errorf("unexpected status %s", resp.Status)
	}
	notes, err := io.ReadAll(resp.Body)
	if err != nil {
		return nil, err
	}
	var releases []release
	for _, m := range headingRE.FindAllStringSubmatch(string(notes), -1) {
		r := release{version: m[1], date: m[2]}
		if n := len(releases); n > 0 && releases[n-1].date < r.date {
			return nil, errors.Errorf("%s is listed below the older %s", r.version, releases[n-1].version)
		}
		if r.musl, err = hasMUSL(r); err != nil {
			return nil, errors.Wrapf(err, "probing %s", r.version)
		}
		releases = append(releases, r)
	}
	return releases, nil
}

func hasMUSL(r release) (bool, error) {
	resp, err := http.Head(fmt.Sprintf(muslURL, r.date, r.version))
	if err != nil {
		return false, err
	}
	resp.Body.Close()
	switch resp.StatusCode {
	case http.StatusOK:
		return true, nil
	case http.StatusNotFound:
		return false, nil
	}
	return false, errors.Errorf("unexpected status %s", resp.Status)
}

const header = `// Copyright 2026 Google LLC
// SPDX-License-Identifier: Apache-2.0

// Code generated by gen_rust_releases.go. DO NOT EDIT.
// Regenerate: go generate ./pkg/registry/cratesio

package cratesio

// releases lists the Rust releases, newest first.
var releases = []release{
`

func writeTable(releases []release) error {
	var buf bytes.Buffer
	buf.WriteString(header)
	for _, r := range releases {
		fmt.Fprintf(&buf, "newRelease(%q, %q, %t),\n", r.version, r.date, r.musl)
	}
	buf.WriteString("}\n")
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return errors.Wrap(err, "formatting generated code")
	}
	return os.WriteFile(outputFile, formatted, 0644)
}
